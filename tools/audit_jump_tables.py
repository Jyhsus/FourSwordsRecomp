"""Audit gba_recompile's auto-detected jump tables and emit TOML overrides.

Usage: python tools/audit_jump_tables.py ROM LOG [LOG...] > symbols/AZLE_symbols.toml

Each LOG is gba_recompile output, ideally run with GBARECOMP_JT_REPORT=1 so
every emitted table is listed ("[jt] base=... BX bound=no got=N -> EMIT").

Unbounded ("BX walked") tables have no CMP bound, so the finder walks until
an entry stops looking like code. In AZLE that walk often runs into the next
table or into data, and the extra entries seed ARM "functions" in data; one
of them reaches the 0xFF padding at the end of the ROM and the function count
explodes to ~490k. Every table in one Thumb switch has odd (Thumb) entries
pointing into the code range, so the plausible length is the longest such
prefix. A manual [[jump_table]] at the same address replaces the auto one.
"""
import re
import struct
import sys

ROM_BASE = 0x08000000
CODE_END = 0x08138000  # last code in AZLE; data and tables follow

rom = open(sys.argv[1], "rb").read()
log = "".join(open(path, errors="ignore").read() for path in sys.argv[2:])

tables = {}  # base -> (largest count seen, dispatch site)
patterns = (r"auto_jt 0x([0-9A-F]+) count=(\d+) stride=4 site=0x([0-9A-F]+) BX walked",
            r"\[jt\] base=0x([0-9A-F]+) site=0x([0-9A-F]+) BX\s+bound=no\s+want=0 got=(\d+) -> EMIT")
for m in re.finditer(patterns[0], log):
    tables[int(m[1], 16)] = max(tables.get(int(m[1], 16), (0, 0)), (int(m[2]), int(m[3], 16)))
for m in re.finditer(patterns[1], log):
    tables[int(m[1], 16)] = max(tables.get(int(m[1], 16), (0, 0)), (int(m[3]), int(m[2], 16)))

print("# Generated by tools/audit_jump_tables.py: over-sized auto jump tables,")
print("# trimmed to their Thumb-in-code prefix. Regenerate rather than hand-edit:")
print("# recompile with GBARECOMP_JT_REPORT=1 into a scratch dir, then rerun the")
print("# script on that log (and earlier ones) until regen succeeds.")
for base, (count, site) in sorted(tables.items()):
    if not (ROM_BASE <= base < ROM_BASE + len(rom)):
        continue
    words = [struct.unpack_from("<I", rom, base - ROM_BASE + 4 * i)[0] for i in range(count)]
    keep = 0
    for w in words:
        if not (w & 1) or not (ROM_BASE <= w < CODE_END):
            break
        keep += 1
    if keep == count:
        continue
    if keep < 2:
        print(f"# 0x{base:08X} (site 0x{site:08X}): no plausible Thumb prefix, left alone",
              file=sys.stderr)
        continue
    print()
    print("[[jump_table]]")
    print(f"addr         = 0x{base:08X}")
    print("stride       = 4")
    print(f"count        = {keep}")
    print('format       = "abs32"')
    print('entries_mode = "auto"')
    print(f'note         = "dispatch at 0x{site:08X}; auto walk read {count}, '
          f'entry {keep} = 0x{words[keep]:08X} is not Thumb code"')
